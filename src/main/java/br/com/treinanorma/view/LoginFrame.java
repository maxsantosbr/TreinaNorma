    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String usuario = txtUsuario.getText().trim();
        String senha = new String(campoSenha.getPassword());

        if (usuario.isEmpty() || senha.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Informe usuário e senha.", "Atenção",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        Usuario logado;
        try {
            logado = new br.com.treinanorma.dao.UsuarioDAO().autenticar(usuario, senha);
        } catch (RuntimeException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,"Erro ao acessar o banco:\n" + ex.getMessage(), "Erro",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (logado == null) {
            javax.swing.JOptionPane.showMessageDialog(this,"Usuário ou senha inválidos.", "Acesso negado",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            campoSenha.setText("");
            campoSenha.requestFocusInWindow();
            return;
        }

        br.com.treinanorma.util.Sessao.iniciar(logado);
        new MainFrame().setVisible(true);
        setVisible(false);
        dispose();
    }//GEN-LAST:event_btnLoginActionPerformed

